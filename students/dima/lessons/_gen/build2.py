def stmt_or_gen(r, name, lv, seen):
    return B.uniq(r, name, lv, seen)


def oge_block(r, seen, nums, per=2, src=True):
    out = []
    for n in nums:
        out.append(f"@tasks №{n} — {OGE_NAME[n]}")
        for i in range(per):
            g = OGE[n][i % len(OGE[n])]
            t = B.uniq(r, g, 2, seen)
            if t: out.append(B.emit(t, src=f"Прототип ОГЭ №{n}" if src else None))
    return out


def build_story(n, slug, title, arch, skills, hw):
    r = random.Random(3000 + n); seen = set()
    secs = sections((ARCH / arch).read_text(encoding="utf-8"))
    out = [f"@title {title}", "@tags ОГЭ №1–5 | практика", "@teacher",
           SCHEME.format(idea="сюжетные задачи №1–5. Сначала две «подготовительные» ступени на нужные навыки, потом сам сюжет ОГЭ (ступень 3). Сюжет читать вслух вместе, подписать на рисунке/в таблице всё известное.",
                         mistakes="бросает сюжет, увидев длинный текст. Правило: задачи 1–5 независимы — не получилась одна, переходи к следующей. Мини-срез здесь — сам сюжет: сколько из 5 верно → ×2 в журнал.")]
    out += warmup(n, r, seen)
    out.append("@theory Как решать сюжет №1–5")
    out.append("""<ol class="ls-steps"><li>Прочитать <b>весь</b> текст, не решая. Подчеркнуть числа.</li><li>Подписать на рисунке или в таблице, что есть что.</li>
<li>Каждую задачу 1–5 решать отдельно; не вышло — пропустить.</li><li>Перед ответом — проверить единицы (м, см, руб., мин).</li></ol>
<div class="ls-warn">Обычно задачи 1–2 самые лёгкие (найти в таблице, посчитать по рисунку) — их нельзя терять.</div>""")
    for i, (stitle, items) in enumerate(skills, 1):
        out.append(f"@tasks Ступень {i}. {stitle}")
        for name, lv, k in items:
            for _ in range(k):
                t = B.uniq(r, name, lv, seen)
                if t: out.append(B.emit(t))
    for cmd, head, body in secs:
        if cmd == "theory":
            out.append("@theory " + (head or "Условие сюжета и подсказки"))
            out.append(body)
        if cmd == "practice":
            out.append("@tasks Ступень 3. Сюжет ОГЭ")
            out.append(strip_rep(body).strip())
    out += hw_block(n, r, seen, hw)
    write(n, slug, out)


