def sections(text):
    """Разбить .lesson на [(команда, заголовок, тело)]."""
    out, cur = [], None
    for line in text.splitlines():
        m = re.match(r"^@(title|tags|teacher|theory|card|practice|hw|tasks)\b ?(.*)$", line)
        if m:
            cur = [m.group(1), m.group(2), []]; out.append(cur)
        elif cur is not None:
            cur[2].append(line)
    return [(a, b, "\n".join(c)) for a, b, c in out]


def strip_rep(body):
    return "\n".join(l for l in body.splitlines() if not l.startswith("@rep "))


def warmup(n, r, seen):
    out = ["@tasks Разминка-повторение (12 минут)"]
    picked = []
    for b in (n - 1, n - 2, n - 4, n - 7):
        b = max(b, 3)
        for name in r.sample(CORE[b], min(2, len(CORE[b]))):
            t = B.uniq(r, name, 2, seen)
            if t: picked.append((t, b))
    picked = picked[:6] + [(B.uniq(r, "table_div", 2, seen), 8), (B.uniq(r, r.choice(["eq_all6", "eq2_mix"]), 2, seen), 14)]
    return out + [B.emit(t, rep=b) for t, b in picked]


def hw_block(n, r, seen, items):
    out = ["@hw"]
    for name, lv, k in items:
        for _ in range(k):
            t = B.uniq(r, name, lv, seen)
            if t: out.append(B.emit(t))
    for b in (n - 2, n - 4, n - 8):
        t = B.uniq(r, r.choice(CORE[max(b, 3)]), 2, seen)
        if t: out.append(B.emit(t, rep=b))
    return out


