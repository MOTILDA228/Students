#!/usr/bin/env python3.12
"""Пакет ДЗ по дробям (урок 07a): 6 домашних заданий по 12 задач, от простого к сложному."""
import random
import build as B

SETS = [
    ("ДЗ 1. Что такое дробь, доля от числа", [("fr_part", 1, 6), ("fr_reduce", 1, 6)]),
    ("ДЗ 2. Сокращение и одинаковые знаменатели", [("fr_reduce", 1, 4), ("fr_add_same", 1, 8)]),
    ("ДЗ 3. Сложение с разными знаменателями", [("fr_add_same", 1, 2), ("fr_add", 1, 10)]),
    ("ДЗ 4. Вычитание", [("fr_add", 2, 3), ("fr_sub", 2, 9)]),
    ("ДЗ 5. Умножение и деление", [("fr_mul", 1, 6), ("fr_div", 2, 6)]),
    ("ДЗ 6. Смешанные числа и всё вместе", [("fr_to_improper", 1, 3), ("fr_mixed", 2, 3), ("fr_add", 2, 2), ("fr_sub", 2, 2), ("fr_mul", 2, 1), ("fr_div", 2, 1)]),
]

r = random.Random("дз-дроби"); seen = set()
out = ["@title Урок 7a. Домашние задания: дроби (6 вариантов)", "@tags ДЗ | дроби | ОГЭ №6", "@teacher",
       """<p><b>Как использовать:</b> 6 готовых домашних заданий по 12 задач, от самого простого к уровню ОГЭ. Давать по одному ДЗ после каждого урока, по порядку: ДЗ 1 → ДЗ 6. Печатать кнопкой «Печать для ученика» (решения не печатаются), или показывать в «Режиме ученика».</p>
<p><b>Правило:</b> не сделал ДЗ — решает его первые 10 минут урока при вас. Проверка — по ответам ниже; 10–12 верных → следующее ДЗ, меньше 8 → дать то же ДЗ ещё раз (в генераторе можно сделать новый вариант).</p>
<p>Шпаргалка ниже — пусть лежит у него перед глазами, пока решает.</p>""",
       "@theory Шпаргалка по дробям",
       """<div class="ls-rule">\\(\\frac{3}{4}\\): целое разрезали на <b>4</b> части (знаменатель), взяли <b>3</b> (числитель).</div>
<div class="ls-rule"><b>Доля от числа:</b> \\(\\frac{2}{3}\\) от 15: делим на знаменатель (\\(15 : 3 = 5\\)), умножаем на числитель (\\(5\\cdot2 = 10\\)).</div>
<div class="ls-rule"><b>Сокращение:</b> числитель и знаменатель делим на одно число: \\(\\frac{12}{18} = \\frac{2}{3}\\) (на 6).</div>
<div class="ls-rule"><b>Одинаковые знаменатели:</b> складываем/вычитаем только числители: \\(\\frac{2}{7} + \\frac{3}{7} = \\frac{5}{7}\\).</div>
<div class="ls-rule"><b>Разные знаменатели — 4 шага:</b> 1) общий знаменатель; 2) доп. множители (общий : свой); 3) умножить числители; 4) сложить/вычесть, сократить.<br>\\(\\frac{1}{2} + \\frac{1}{3} = \\frac{3}{6} + \\frac{2}{6} = \\frac{5}{6}\\).</div>
<div class="ls-rule"><b>Умножение:</b> числитель на числитель, знаменатель на знаменатель (сначала сократить крест-накрест). <b>Деление:</b> вторую дробь перевернуть и умножить.</div>
<div class="ls-rule"><b>Смешанное число:</b> \\(2\\frac{3}{4} = \\frac{2\\cdot4 + 3}{4} = \\frac{11}{4}\\).</div>
<div class="ls-warn">Знаменатели НЕ складываются: \\(\\frac{1}{2} + \\frac{1}{3} \\ne \\frac{2}{5}\\). Ответ, если можно, — десятичной дробью (\\(\\frac{1}{2} = 0{,}5\\)) или несократимой дробью.</div>"""]
for title, items in SETS:
    out.append(f"@tasks {title}")
    for name, lv, k in items:
        for _ in range(k):
            t = B.uniq(r, name, lv, seen)
            if t: out.append(B.emit(t))
(B.OUT / "07a-dz-drobi.lesson").write_text("\n".join(out) + "\n", encoding="utf-8")
print("ok")
