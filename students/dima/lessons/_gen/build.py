def make(r, name, lv):
    if name == "__stmt":
        return stmt_tasks(r, 1)
    return [G.GEN[name](r, lv)]


def emit(t, src=None, rep=None):
    s = ["@task"]
    if rep: s.append(f"@rep {rep}")
    elif src: s.append(f"@src {src}")
    s.append(t["q"])
    if t.get("fig"): s.append(t["fig"])
    s += ["@sol", t["sol"], f"@ans {t['ans']}"]
    if t.get("check"): s.append(f"@check {t['check']}")
    return "\n".join(s)


def uniq(r, name, lv, seen, tries=30):
    for _ in range(tries):
        ts = make(r, name, lv)
        if ts and ts[0]["q"] not in seen:
            seen.add(ts[0]["q"]); return ts[0]
    return ts[0] if ts else None


